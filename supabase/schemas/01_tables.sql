-- Advisor-recorded visit (CRM-owned; never touched by the sheet sync).
create table public.visitas (
    id bigint generated by default as identity primary key,
    lead_id bigint not null references public.contacts(id) on delete cascade,
    propiedad_id text references public.propiedades(id),
    fecha timestamp with time zone not null,
    resultado text,
    notas text,
    asesor_id bigint,
    created_at timestamp with time zone not null default now(),
    -- Google Calendar event id: the visit is created as a calendar event (source
    -- of truth) and mirrored here; this keys the Calendar<->CRM sync.
    gcal_event_id text unique,
    -- Mirrored from the calendar event status (confirmada | cancelada). The
    -- calendar_sync sets this; resultado/notas stay CRM-owned.
    estado text default 'confirmada'
);

create index visitas_lead_id_idx on public.visitas using btree (lead_id);

-- M:N lead <-> property relation (synced; relacion explains the link origin).
create table public.lead_propiedad (
    id bigint generated by default as identity primary key,
    lead_id bigint not null references public.contacts(id) on delete cascade,
    propiedad_id text not null references public.propiedades(id) on delete cascade,
    relacion text not null,
    unique (lead_id, propiedad_id, relacion)
);

-- Bot transcript (append-only, synced from the Sheet; read-only in the CRM).
create table public.conversaciones (
    id bigint primary key,
    lead_id bigint not null references public.contacts(id) on delete cascade,
    rol text not null,
    texto text,
    timestamp timestamp with time zone,
    nombre_lead text
);

create index conversaciones_lead_id_timestamp_idx
    on public.conversaciones using btree (lead_id, timestamp);

