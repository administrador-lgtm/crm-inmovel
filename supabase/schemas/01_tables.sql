create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[],
    -- sales ids to notify about this note (@mention). A trigger fans these out
    -- into note_mentions rows (one per recipient, with read state).
    mentions bigint[]
);

-- Per-recipient @mention notification with read state. Spawned by a trigger
-- from contact_notes.mentions; the CRM reads/updates it (bell + "leído").
create table public.note_mentions (
    id bigint generated always as identity primary key,
    note_id bigint references public.contact_notes(id) on delete cascade,
    contact_id bigint references public.contacts(id) on delete cascade,
    recipient_id bigint references public.sales(id),
    sender_id bigint references public.sales(id),
    created_at timestamptz default now(),
    read_at timestamptz
);

create index note_mentions_recipient_unread_idx
    on public.note_mentions(recipient_id) where read_at is null;

-- Small server-side config store (e.g. the notify_mention shared secret). RLS is
-- enabled with no policies so it is unreadable except by SECURITY DEFINER
-- functions / the service role. Values are set at runtime, never committed.
create table public.app_config (
    key text primary key,
    value text
);

-- Reactivation cohorts: phone numbers that received an out-of-pipeline WhatsApp
-- reactivation template, with the cohort and template they got. Materializes the
-- bot's hardcoded REACTIVACION_TELS guard. When such a lead replies, the
-- create_reactivation_note trigger surfaces the reply as a note on the ficha.
create table public.reactivaciones (
    telefono text primary key,
    grupo text,
    template text,
    fecha date default now()
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    -- Inmovel asesor fields (mirrored from the Sheet Asesores tab by the sync)
    telefono text,
    -- WhatsApp number in E.164 (52155...) for mention notifications. `telefono`
    -- is the synced display number (often without country code), so this holds
    -- the send-ready form.
    whatsapp text,
    calendario text,
    linea_negocio text check (linea_negocio in ('exclusiva', 'compartida')),
    activo boolean default true,
    -- Advisors are assigned to a manager; the manager team-scope RLS
    -- (TASK-014) reads leads whose asesor_asignado has this manager_id.
    manager_id bigint references public.sales(id)
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

--
-- Foreign keys
--

alter table public.contacts
    add constraint contacts_sales_id_fkey foreign key (sales_id) references public.sales(id);

alter table public.contact_notes
    add constraint "contactNotes_contact_id_fkey" foreign key (contact_id) references public.contacts(id) on update cascade on delete cascade;

alter table public.contact_notes
    add constraint "contactNotes_sales_id_fkey" foreign key (sales_id) references public.sales(id) on update cascade on delete cascade;

alter table public.sales
    add constraint sales_user_id_fkey foreign key (user_id) references auth.users(id);

-- Legacy primary key constraint names (from before snake_case rename)
alter table only public.contact_notes
    add constraint "contactNotes_pkey" primary key (id);

--
-- Indexes on foreign keys
--

create index contact_notes_contact_id_idx on public.contact_notes using btree (contact_id);

-- Inmovel FK constraints (added after table creation to avoid forward refs)
alter table public.contacts
    add constraint contacts_asesor_asignado_fkey foreign key (asesor_asignado) references public.sales(id);

alter table public.visitas
    add constraint visitas_asesor_id_fkey foreign key (asesor_id) references public.sales(id);
